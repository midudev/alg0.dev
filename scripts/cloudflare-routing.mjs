// @ts-check
import { appendFile, readdir, readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

/** Every HTML route shape the site emits: `/`, `/es/`, `/:slug/`, `/es/:slug/`. */
const HTML_ROUTES = ['/', '/:page/', '/es/:page/']

/** Build output folders that are not standalone pages. */
const NON_PAGE_DIRS = new Set(['_astro', 'algorithm-content', 'algorithm-code', 'og'])

/** @param {string} tag */
function attrs(tag) {
  return Object.fromEntries(
    [...tag.matchAll(/([a-z-]+)(?:="([^"]*)")?/g)].map(([, name, value = '']) => [name, value]),
  )
}

/**
 * `Link` value for the shared client module, stylesheet and fonts, read from the
 * built home page (every page shares the same Layout assets).
 *
 * @param {URL} dir
 */
async function getPreloadLinks(dir) {
  const html = await readFile(new URL('index.html', dir), 'utf8')
  const links = []
  // Client bootstrap: Cloudflare only replays preload/preconnect in the 103, so this
  // one rides on the 200 headers (fetched before the parser reaches the <script>).
  for (const [tag] of html.matchAll(/<script\b[^>]*>/g)) {
    const a = attrs(tag)
    if (a.type === 'module' && a.src?.startsWith('/')) links.push(`<${a.src}>; rel=modulepreload`)
  }
  for (const [tag] of html.matchAll(/<link\b[^>]*>/g)) {
    const a = attrs(tag)
    if (a.rel === 'stylesheet' && a.href?.startsWith('/')) {
      links.push(`<${a.href}>; rel=preload; as=style`)
    } else if (a.rel === 'preload' && a.as === 'font' && a.href?.startsWith('/')) {
      links.push(`<${a.href}>; rel=preload; as=font; type="${a.type}"; crossorigin`)
    }
  }
  return links
}

/**
 * Paths of every page folder (`/bubble-sort`, `/es/bubble-sort`, `/es`), without the
 * trailing slash.
 *
 * @param {URL} dir
 */
async function getPagePaths(dir) {
  const root = fileURLToPath(dir).replace(/\/$/, '')
  const entries = await readdir(root, { recursive: true, withFileTypes: true })
  return entries
    .filter((entry) => entry.isFile() && entry.name === 'index.html')
    .map((entry) => entry.parentPath.slice(root.length))
    .filter((path) => path !== '' && !NON_PAGE_DIRS.has(path.split('/')[1]))
    .sort()
}

/**
 * Cloudflare Workers static-assets routing, generated after the build because it
 * depends on hashed asset names and the final page list:
 *
 * - `_headers`: `Link` preloads for JS, CSS and fonts on HTML routes. Cloudflare replays
 *   the CSS/font preloads as `103 Early Hints`, so the browser fetches them before the
 *   HTML arrives.
 * - `_redirects`: `/slug` → `/slug/` with a 301. Assets `html_handling` would answer
 *   with a temporary 307; a permanent redirect consolidates ranking signals on the
 *   canonical (trailing-slash) URL, including old slashless links.
 *
 * @returns {import('astro').AstroIntegration}
 */
export function cloudflareRouting() {
  return {
    name: 'alg0:cloudflare-routing',
    hooks: {
      'astro:build:done': async ({ dir, logger }) => {
        const links = await getPreloadLinks(dir)
        if (links.length > 0) {
          const value = links.join(', ')
          const block = HTML_ROUTES.map((route) => `${route}\n  Link: ${value}`).join('\n\n')
          await appendFile(new URL('_headers', dir), `\n# Early Hints (generated)\n${block}\n`)
          logger.info(`_headers: ${links.length} Early Hints preloads`)
        } else {
          logger.warn('No stylesheet or font preloads found in index.html; skipping Link headers')
        }

        const pages = await getPagePaths(dir)
        const redirects = pages.map((path) => `${path} ${path}/ 301`).join('\n')
        await writeFile(
          new URL('_redirects', dir),
          `# Generated by scripts/cloudflare-routing.mjs\n${redirects}\n`,
        )
        logger.info(`_redirects: ${pages.length} trailing-slash redirects`)
      },
    },
  }
}
